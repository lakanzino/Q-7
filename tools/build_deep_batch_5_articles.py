def extract_faqs_strict(html_text):
    faqs = []
    m = re.search(r'<h2>پرسش‌های متداول.*?</h2>(.*?)<h2>منابع', html_text, re.DOTALL)
    if m:
        content = m.group(1)
        items = re.findall(r'<h3>(.*?)</h3>\s*<p>(.*?)</p>', content, re.DOTALL)
        for q, a in items:
            q_clean = re.sub(r'<.*?>', '', q).strip()
            a_clean = re.sub(r'<.*?>', '', a).strip()
            faqs.append({'question': q_clean, 'answer': a_clean})
    return faqs

def count_words(text):
    clean = re.sub(r'<.*?>', ' ', text)
    words = [w for w in clean.split() if w.strip()]
    return len(words)

